#Operators

num_1= 10 
num_2= 2

#Addition
print(num_1+num_2)

#Substraction
print(num_1-num_2)

#Multiplication
print(num_1*num_2)

#DIvision 
print(num_1/num_2)

#Floor Division - Provides the Division after removing the Decimal Part
print(num_1//num_2)

#Exponential - Provides the raised value
print(num_1**num_2)

#Modulus - Returns the Reminder After Divison 
print(num_1%num_2)
